#barplot_regression_slope.r is a combined script.
#Fig. 3b is generated by prism using data from  Supplementary Table 6.
GC_subtype_avianFamily_plot.r #plot for Fig. 4a and Extended Data Fig. 3 using data in genomic_feature/GC_subtype_avianFamily_data
#Fig. 5d is generated by prism using data saved in genomic_features/recentH5_HuH3N8_genomic_gc_content.csv
r violin_avian_HA_NA.r #generates Supplementary Fig. 11 using data in genomic_feature/GC_subtype_avianFamily_data

#Part 4. codon usage bias
cd codon_bias
