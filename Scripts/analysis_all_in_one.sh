cai_plot.m #plot for Extended Data Fig. 1

#Part 5. RNA secondary structure
cd RNA_secondary_structure
./runRNAfold.sh #run ViennaRNA-2.6.4/RNAfold to compute the free energy of RNA folding 
mono RNAfold_script.exe 
#RNAfold_script.cs is a combined script to extract the free energy of RNA folding 
#from the outputs of the tool ViennaRNA-2.6.4/RNAfold,
#and map to GC/GC12/GC3 contents.
